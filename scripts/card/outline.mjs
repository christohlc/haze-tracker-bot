// One-off: turn URA's Master Plan 2019 subzone boundaries (data.gov.sg, "Subzone Boundary
// (No Sea)" GeoJSON, Singapore Open Data Licence) into the island silhouette that the summary
// card draws, already projected into card pixels. Writes scripts/card/singapore.svg, which
// build-assets.mjs rasterises. Rerun only if the card's map placement changes.
//
//   node scripts/card/outline.mjs path/to/subzones.geojson

import { readFileSync, writeFileSync } from 'node:fs';
import { CARD_H, CARD_W, MAP } from '../../tgcloud/lib/card/geometry.js';

const geo = JSON.parse(readFileSync(process.argv[2], 'utf8'));

/** @param {[number, number]} p lon, lat → card px */
const project = ([lon, lat]) => [MAP.x + (lon - MAP.lon) * MAP.scale, MAP.y - (lat - MAP.lat) * MAP.scale];

/** Douglas–Peucker. @param {number[][]} pts @param {number} tol */
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = /** @type {[number, number]} */ (stack.pop());
    const [ax, ay] = pts[a];
    const [bx, by] = pts[b];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    let worst = -1;
    let dmax = tol;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len;
      if (d > dmax) (dmax = d), (worst = i);
    }
    if (worst > 0) {
      keep[worst] = 1;
      stack.push([a, worst], [worst, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

/** @param {number[][]} ring */
const area = (ring) => Math.abs(ring.reduce((s, [x, y], i) => {
  const [nx, ny] = ring[(i + 1) % ring.length];
  return s + x * ny - nx * y;
}, 0)) / 2;

const rings = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    // Outer rings only: subzones tile the land, so holes are other subzones.
    // A closed ring starts and ends on the same point, which Douglas–Peucker can't use as a
    // baseline, so simplify it as two halves split at the point farthest from the start.
    const pts = poly[0].map(project);
    let far = 0;
    let farDist = 0;
    pts.forEach(([x, y], i) => {
      const d = Math.hypot(x - pts[0][0], y - pts[0][1]);
      if (d > farDist) (far = i), (farDist = d);
    });
    const ring = [...simplify(pts.slice(0, far + 1), 0.6), ...simplify(pts.slice(far), 0.6).slice(1, -1)];
    if (ring.length >= 3 && area(ring) >= 6) rings.push(ring);
  }
}

const d = rings
  .map((r) => `M${r.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`)
  .join('');
writeFileSync(
  new URL('./singapore.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" width="${CARD_W}" height="${CARD_H}" viewBox="0 0 ${CARD_W} ${CARD_H}">
<!-- Generated by outline.mjs from URA Master Plan 2019 subzone boundaries (data.gov.sg). Filled and
     stroked in one colour so the subzone seams disappear. -->
<path fill="#000" stroke="#000" stroke-width="1.2" stroke-linejoin="round" d="${d}"/>
</svg>
`,
);
console.log(`${rings.length} rings, ${d.length} chars`);
