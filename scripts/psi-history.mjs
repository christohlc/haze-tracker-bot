// Build tgcloud/lib/psi-history.js: every SGT day since Feb 2016 whose haze took the official
// 24-hour PSI above 100 in some region, with that day's highest, for "highest since…"
// (lib/psi-record.js). An hour counts only as high as its particle sub-index (PM2.5 or PM10), so
// ozone spikes and one-hour glitches (West's 170 on 26 Jul 2016) don't count as haze.
// NEA's yearly datasets on data.gov.sg cover 2016–2024; later days come from NEA's day API, one
// request a second, slowed further by 429s (~25 min a year).
// Run: node scripts/psi-history.mjs           adds the days since the file's THROUGH
//      node scripts/psi-history.mjs --full    rebuilds from 2016
import { existsSync } from 'node:fs';
import { writeFileSync } from 'node:fs';

// data.gov.sg's "Historical Pollutant Standards Index (PSI)" collection (2215), one dataset a year.
const YEARS = {
  2016: 'd_ad4fd39ae771a7194d9aee2b99ce04af',
  2017: 'd_3f0f79298b18c4ec2aa1615dc9f0acd6',
  2018: 'd_f4f9c7c443fd60987dbd020b7076e65b',
  2019: 'd_1d7c9dbe3f747492579793d72fbbab1c',
  2020: 'd_36ed5dfd3b3b6e69324fa03f4068bb13',
  2021: 'd_05b35c51664e1bb6f4dcd78478ae1abe',
  2022: 'd_d3fb32451d63dc48dc425146ec014516',
  2023: 'd_10501b71361f97dbbbab82095406c9c5',
  2024: 'd_9213cd2e4631f7148ab5932a10df9958',
};
const REGIONS = ['north', 'south', 'east', 'west', 'central'];
const FROM_API = '2025-01-01';
const OUT = new URL('../tgcloud/lib/psi-history.js', import.meta.url);

/** An hour's haze: the 24-hour PSI, but no higher than its particle sub-index. */
const hazePsi = (psi, pm25Sub, pm10Sub) => {
  const particles = Math.max(pm25Sub ?? -1, pm10Sub ?? -1);
  return particles >= 0 ? Math.min(psi, particles) : psi;
};

/** date → that day's highest regional haze PSI */
const days = new Map();
const note = (date, psi) => {
  if (Number.isFinite(psi) && psi > (days.get(date) ?? -1)) days.set(date, psi);
};
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const nextDay = (d) => new Date(Date.parse(`${d}T00:00:00Z`) + 86_400_000).toISOString().slice(0, 10);

async function getJson(url) {
  for (let i = 0; i < 5; i++) {
    const res = await fetch(url);
    if (res.status === 429) {
      await sleep(5_000 * (i + 1));
      continue;
    }
    return res.json();
  }
  throw new Error(`429s from ${url}`);
}

const full = process.argv.includes('--full') || !existsSync(OUT);
let from = FROM_API;
if (full) {
  for (const [year, id] of Object.entries(YEARS)) {
    const poll = await getJson(`https://api-open.data.gov.sg/v1/public/api/datasets/${id}/poll-download`);
    if (!poll.data?.url) throw new Error(`${year}: no download (${JSON.stringify(poll).slice(0, 200)})`);
    const [head, ...lines] = (await (await fetch(poll.data.url)).text()).trim().split('\n');
    const col = head.split(',');
    const at = (f, c) => Number.parseFloat(f[col.indexOf(c)]);
    for (const line of lines) {
      const f = line.split(',');
      if (!REGIONS.includes(f[col.indexOf('region')])) continue;
      const sub = (c) => (Number.isFinite(at(f, c)) ? at(f, c) : null);
      note(f[col.indexOf('timestamp')].slice(0, 10), hazePsi(at(f, 'psi_twenty_four_hourly'), sub('pm25_sub_index'), sub('pm10_sub_index')));
    }
    console.log(year, lines.length, 'rows');
  }
} else {
  const old = await import(OUT.href);
  for (const [d, v] of old.PEAKS) days.set(d, v);
  from = nextDay(old.THROUGH);
}

const yesterday = new Date(Date.now() + 8 * 3_600_000 - 86_400_000).toISOString().slice(0, 10);
for (let d = from; d <= yesterday; d = nextDay(d)) {
  const body = await getJson(`https://api.data.gov.sg/v1/environment/psi?date=${d}`);
  for (const { readings: r } of body.items ?? [])
    for (const g of REGIONS) note(d, hazePsi(r?.psi_twenty_four_hourly?.[g], r?.pm25_sub_index?.[g], r?.pm10_sub_index?.[g]));
  if (d.endsWith('-01')) console.log(d);
  await sleep(1_000);
}

const peaks = [...days].filter(([, psi]) => psi > 100).sort(([a], [b]) => a.localeCompare(b));
writeFileSync(
  OUT,
  `// @ts-check
// Generated by scripts/psi-history.mjs from NEA's 24-hour PSI (data.gov.sg). Don't edit by hand.
// Every SGT day from Feb 2016 to ${yesterday} whose highest regional 24-hour PSI was above 100, each
// hour counted no higher than its particle sub-index (PM2.5 or PM10), so ozone and glitches don't count.

/** Last day covered. */
export const THROUGH = '${yesterday}';

/** @type {Array<[string, number]>} [SGT date, highest regional 24-hour PSI from particles] */
export const PEAKS = ${JSON.stringify(peaks)};
`,
);
console.log(`wrote tgcloud/lib/psi-history.js: ${peaks.length} days above 100 through ${yesterday}`);
