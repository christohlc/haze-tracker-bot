// Builds src/lib/coast.ts, the land the Mini App's haze map is drawn on, from Natural Earth's
// public-domain land polygons (naturalearthdata.com). Run after changing MAP_BOUNDS:
//   curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_10m_land.geojson
//   node scripts/hazemap/coast.mjs ne_10m_land.geojson
import { readFileSync, writeFileSync } from 'node:fs';
import { MAP_BOUNDS } from '../../tgcloud/lib/hazemap-parse.js';

const SCALE = 16; // SVG units per degree, so the map is 400 × 288
const TOLERANCE = 0.03; // degrees (~half an SVG unit)
const MIN_AREA = 0.004; // square degrees: drops specks, keeps Singapore
const { west, east, south, north } = MAP_BOUNDS;
// Clip a little outside the view so no coast edge shows at the frame.
const box = { west: west - 0.5, east: east + 0.5, south: south - 0.5, north: north + 0.5 };

/** Sutherland–Hodgman against one edge. */
function clipEdge(ring, inside, cross) {
  const out = [];
  for (let i = 0; i < ring.length; i++) {
    const a = ring[i];
    const b = ring[(i + 1) % ring.length];
    if (inside(b)) {
      if (!inside(a)) out.push(cross(a, b));
      out.push(b);
    } else if (inside(a)) out.push(cross(a, b));
  }
  return out;
}
const atX = (x) => (a, b) => [x, a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0])];
const atY = (y) => (a, b) => [a[0] + ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]), y];
function clip(ring) {
  let r = ring;
  r = clipEdge(r, (p) => p[0] >= box.west, atX(box.west));
  r = clipEdge(r, (p) => p[0] <= box.east, atX(box.east));
  r = clipEdge(r, (p) => p[1] >= box.south, atY(box.south));
  r = clipEdge(r, (p) => p[1] <= box.north, atY(box.north));
  return r;
}

/** Douglas–Peucker. */
function simplify(pts) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    const [ax, ay] = pts[s];
    const [bx, by] = pts[e];
    const len = Math.hypot(bx - ax, by - ay) || 1;
    let max = 0;
    let at = -1;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / len;
      if (d > max) (max = d), (at = i);
    }
    if (max > TOLERANCE) {
      keep[at] = 1;
      stack.push([s, at], [at, e]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

const area = (r) => Math.abs(r.reduce((s, p, i) => s + p[0] * r[(i + 1) % r.length][1] - r[(i + 1) % r.length][0] * p[1], 0) / 2);
const n = (v) => +v.toFixed(1);
const project = ([lon, lat]) => [n((lon - west) * SCALE), n((north - lat) * SCALE)];

const geo = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const paths = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      const clipped = clip(ring.slice(0, -1));
      if (clipped.length < 3 || area(clipped) < MIN_AREA) continue;
      const pts = simplify(clipped).map(project);
      if (pts.length < 3) continue;
      paths.push(`M${pts.map((p) => p.join(' ')).join('L')}Z`);
    }
  }
}
const d = paths.join('');
writeFileSync(
  new URL('../../src/lib/coast.ts', import.meta.url),
  `// Generated by scripts/hazemap/coast.mjs from Natural Earth (public domain). Don't edit by hand.\n` +
    `// Land inside MAP_BOUNDS, in SVG units of ${SCALE} per degree (x east from ${west}°E, y south from ${north}°N).\n` +
    `export const SCALE = ${SCALE};\nexport const WIDTH = ${(east - west) * SCALE};\nexport const HEIGHT = ${(north - south) * SCALE};\n` +
    `export const LAND = '${d}';\n`,
);
console.log(`${paths.length} rings, ${d.length} chars`);
